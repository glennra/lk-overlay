#!/usr/bin/env python3
"""Generate a compact, row-deduplicated ARGB animation from the source GIF.

Requires Pillow. Run from any directory; --check verifies the checked-in data.
"""
import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent
SOURCE = ROOT / "wo046_animation.gif"
DEST = ROOT / "wo046_animation_data.h"


def array(name, ctype, values, columns=12):
    lines = [f"static const {ctype} {name}[] = {{"]
    for i in range(0, len(values), columns):
        lines.append("  " + ", ".join(str(v) for v in values[i:i + columns]) + ",")
    return "\n".join(lines + ["};", ""])


def generate():
    image = Image.open(SOURCE)
    if image.size != (800, 480) or image.n_frames != 13:
        raise ValueError("unexpected GIF geometry or frame count")
    palette = []
    color_ids = {}
    runs = []
    row_offsets = []
    rows_seen = {}
    durations = []
    for frame in range(image.n_frames):
        image.seek(frame)
        durations.append(image.info.get("duration", 0))
        rgb = image.convert("RGB")  # Pillow composites GIF disposal/offsets.
        for y in range(image.height):
            colors = list(rgb.crop((0, y, image.width, y + 1)).getdata())
            encoded = []
            last = colors[0]
            for x in range(1, image.width + 1):
                if x == image.width or colors[x] != last:
                    if last not in color_ids:
                        color_ids[last] = len(palette)
                        palette.append(0xff000000 | last[0] << 16 | last[1] << 8 | last[2])
                    encoded.append((x << 8) | color_ids[last])
                    if x < image.width:
                        last = colors[x]
            key = tuple(encoded)
            if key not in rows_seen:
                rows_seen[key] = len(runs)
                runs.extend(encoded)
            row_offsets.append(rows_seen[key])
    if len(palette) > 256 or len(runs) >= 65536 or any(d <= 0 for d in durations):
        raise ValueError("GIF exceeds asset format limits")
    return ("/* Generated by generate_asset.py from wo046_animation.gif; do not edit. */\n"
            "#pragma once\n#include <stdint.h>\n\n"
            "#define WO046_WIDTH 800u\n#define WO046_HEIGHT 480u\n"
            f"#define WO046_FRAMES {image.n_frames}u\n\n"
            + array("wo046_palette", "uint32_t", palette, 8)
            + array("wo046_row_offsets", "uint16_t", row_offsets)
            + array("wo046_runs", "uint32_t", runs)
            + array("wo046_durations_ms", "uint16_t", durations))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = generate()
    if args.check:
        if not DEST.exists() or DEST.read_text() != result:
            raise SystemExit("generated animation data is out of date")
    else:
        DEST.write_text(result)
